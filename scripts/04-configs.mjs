// Step 4: generate one config per (group, tool) from rules/groups.json.
//
// Every rule is set to "error" with its default options (the recommended
// presets do not pass options to any rule in the universe). Nothing else is
// enabled: Oxlint's default `correctness` category and Biome's recommended
// preset are switched off, and Biome's formatter/assist are disabled.
//
// The runner copies these files into the fixture root for the duration of a
// run, so relative globs, tsconfig discovery and Biome's project scanner all
// resolve against the fixture.
//
// Output: configs/group-{a,b}/{eslint.config.mjs, rslint.config.mjs, oxlintrc.json, biome.json}
import fs from 'node:fs';
import path from 'node:path';
import { CONFIGS_DIR, RULES_DIR, readJson, writeJson } from './lib.mjs';

const groups = readJson(path.join(RULES_DIR, 'groups.json'));
const TS_FILES = '**/*.{ts,tsx,mts,cts}';

// ESLint configs are copied into fixtures that have their own (different)
// typescript-eslint installed, so import the benchmark's copy by absolute URL.
const tseslintUrl = import.meta.resolve('typescript-eslint');

const header = (group) => `// Generated by scripts/04-configs.mjs - group ${group}. Do not edit.\n`;

function eslintConfig(group, rules) {
  return `${header(group)}import tseslint from '${tseslintUrl}';

export default [
  {
    files: ['${TS_FILES}'],
    languageOptions: {
      parser: tseslint.parser,
      parserOptions: { projectService: true, tsconfigRootDir: import.meta.dirname },
    },
    linterOptions: { reportUnusedDisableDirectives: 'off' },
    plugins: { '@typescript-eslint': tseslint.plugin },
    rules: ${JSON.stringify(Object.fromEntries(rules.map((r) => [r.eslint, 'error'])), null, 6).replace(/\n}$/, '\n    }')},
  },
];
`;
}

function rslintConfig(group, rules) {
  return `${header(group)}export default [
  {
    files: ['${TS_FILES}'],
    languageOptions: { parserOptions: { projectService: true } },
    plugins: ['@typescript-eslint'],
    rules: ${JSON.stringify(Object.fromEntries(rules.map((r) => [r.rslint, 'error'])), null, 6).replace(/\n}$/, '\n    }')},
  },
];
`;
}

function oxlintConfig(rules) {
  const off = ['correctness', 'suspicious', 'pedantic', 'perf', 'style', 'restriction', 'nursery'];
  return {
    plugins: ['eslint', 'typescript'],
    categories: Object.fromEntries(off.map((c) => [c, 'off'])),
    rules: Object.fromEntries(rules.map((r) => [r.oxlint, 'error'])),
  };
}

function biomeConfig(rules) {
  const byGroup = {};
  for (const { biome } of rules) {
    const [group, name] = biome.split('/');
    (byGroup[group] ??= {})[name] = 'error';
  }
  return {
    root: true,
    vcs: { enabled: false },
    files: { maxSize: 64 * 1024 * 1024 },
    formatter: { enabled: false },
    assist: { enabled: false },
    linter: { enabled: true, rules: { preset: 'none', ...byGroup } },
  };
}

for (const [group, { tools, rules }] of Object.entries(groups)) {
  const dir = path.join(CONFIGS_DIR, `group-${group.toLowerCase()}`);
  fs.rmSync(dir, { recursive: true, force: true });
  fs.mkdirSync(dir, { recursive: true });
  if (tools.includes('eslint')) fs.writeFileSync(path.join(dir, 'eslint.config.mjs'), eslintConfig(group, rules));
  if (tools.includes('rslint')) fs.writeFileSync(path.join(dir, 'rslint.config.mjs'), rslintConfig(group, rules));
  if (tools.includes('oxlint')) writeJson(path.join(dir, 'oxlintrc.json'), oxlintConfig(rules));
  if (tools.includes('biome')) writeJson(path.join(dir, 'biome.json'), biomeConfig(rules));
  console.log(`group ${group}: ${fs.readdirSync(dir).join(', ')}`);
}
