// Step 4: generate one config per (group, fixture, tool).
//
// Rules: from rules/groups.json. Every rule is set to "error" with its default
// options (the recommended presets do not pass options to any rule in the
// universe). Nothing else is enabled: Oxlint's default `correctness` category
// and Biome's recommended preset are switched off, and Biome's formatter and
// assist are disabled.
//
// Files: from scope/<fixture>.json. Each tool runs on the fixture root and its
// config selects the scope: JS/TS files, minus the repository's lint ignores,
// minus gitignored files by exact path. Tools that lint Vue/Svelte/Astro by
// default ignore those files. An override turns type-aware rules off for the
// `untyped` files (no TypeScript project includes them); ESLint and Rslint
// also turn projectService off there.
//
// The runner copies these files into the fixture root for the duration of a
// run, so globs, tsconfig discovery and Biome's project scanner all resolve
// against the fixture.
//
// Output: configs/group-{a,b}/<fixture>/{eslint.config.mjs, rslint.config.mjs, oxlintrc.json, biome.json}
import fs from 'node:fs';
import path from 'node:path';
import { CONFIGS_DIR, FIXTURES, RULES_DIR, SCOPE_DIR, readJson, writeJson } from './lib.mjs';

const groups = readJson(path.join(RULES_DIR, 'groups.json'));

const SOURCE_FILES = ['**/*.js', '**/*.jsx', '**/*.mjs', '**/*.cjs', '**/*.ts', '**/*.tsx', '**/*.mts', '**/*.cts'];
const OTHER_FILES = ['**/*.vue', '**/*.svelte', '**/*.astro'];
// The benchmark's own config files, copied into the fixture root during a run.
const BENCH_CONFIGS = ['eslint.config.bench.mjs', 'rslint.config.bench.mjs'];

// ESLint configs are copied into fixtures that have their own (different)
// typescript-eslint installed, so import the benchmark's copy by absolute URL.
const tseslintUrl = import.meta.resolve('typescript-eslint');

/**
 * Patterns that keep everything outside the scope out. `anchor` prefixes exact
 * paths with "/" for gitignore-style matchers (Oxlint), where a pattern without
 * a slash, such as a root-level `rstack.config.ts`, would match at any depth.
 */
function scopeIgnores(fixture, { anchor = false } = {}) {
  const { ignores, exclude } = readJson(path.join(SCOPE_DIR, `${fixture}.json`));
  assertNoGlobSyntax(fixture, exclude);
  const exact = [...BENCH_CONFIGS, ...exclude];
  return [...OTHER_FILES, ...ignores, ...exact.map((p) => (anchor ? `/${p}` : p))];
}

/** Globs of the files where type-aware rules are turned off. */
function untypedFiles(fixture) {
  const { untyped } = readJson(path.join(SCOPE_DIR, `${fixture}.json`));
  assertNoGlobSyntax(fixture, untyped.map((g) => g.replace(/(^|\/)\*\*$/, '')));
  return untyped;
}

// Exact paths are written as globs, so they must not contain glob syntax.
function assertNoGlobSyntax(fixture, paths) {
  const bad = paths.find((p) => /[[\]*?{}()!+@]/.test(p));
  if (bad) throw new Error(`${fixture}: path contains glob characters: ${bad}`);
}

const typedRuleNames = (rules, tool) => rules.filter((r) => r.typed).map((r) => r[tool]);
const offMap = (names) => Object.fromEntries(names.map((name) => [name, 'off']));

const header = (group, fixture) => `// Generated by scripts/04-configs.mjs - group ${group}, ${fixture}. Do not edit.\n`;
const js = (value, indent) => JSON.stringify(value, null, 2).replace(/\n/g, `\n${' '.repeat(indent)}`);
const ruleMap = (rules, tool) => Object.fromEntries(rules.map((r) => [r[tool], 'error']));

function eslintConfig(group, fixture, rules) {
  const untyped = untypedFiles(fixture);
  const untypedBlock = untyped.length
    ? `
  {
    files: ${js(untyped, 4)},
    languageOptions: { parserOptions: { projectService: false, project: false } },
    rules: ${js(offMap(typedRuleNames(rules, 'eslint')), 4)},
  },`
    : '';
  return `${header(group, fixture)}import tseslint from '${tseslintUrl}';

export default [
  {
    ignores: ${js(scopeIgnores(fixture), 4)},
  },
  {
    files: ${js(SOURCE_FILES, 4)},
    languageOptions: {
      parser: tseslint.parser,
      parserOptions: { projectService: true, tsconfigRootDir: import.meta.dirname },
    },
    linterOptions: { reportUnusedDisableDirectives: 'off' },
    plugins: { '@typescript-eslint': tseslint.plugin },
    rules: ${js(ruleMap(rules, 'eslint'), 4)},
  },${untypedBlock}
];
`;
}

function rslintConfig(group, fixture, rules) {
  const untyped = untypedFiles(fixture);
  const untypedBlock = untyped.length
    ? `
  {
    files: ${js(untyped, 4)},
    languageOptions: { parserOptions: { projectService: false, project: false } },
    rules: ${js(offMap(typedRuleNames(rules, 'rslint')), 4)},
  },`
    : '';
  return `${header(group, fixture)}export default [
  {
    ignores: ${js(scopeIgnores(fixture), 4)},
  },
  {
    files: ${js(SOURCE_FILES, 4)},
    languageOptions: { parserOptions: { projectService: true } },
    plugins: ['@typescript-eslint'],
    rules: ${js(ruleMap(rules, 'rslint'), 4)},
  },${untypedBlock}
];
`;
}

function oxlintConfig(fixture, rules) {
  const off = ['correctness', 'suspicious', 'pedantic', 'perf', 'style', 'restriction', 'nursery'];
  return {
    plugins: ['eslint', 'typescript'],
    categories: Object.fromEntries(off.map((c) => [c, 'off'])),
    ignorePatterns: scopeIgnores(fixture, { anchor: true }),
    rules: ruleMap(rules, 'oxlint'),
    overrides: untypedFiles(fixture).length ? [{ files: untypedFiles(fixture), rules: offMap(typedRuleNames(rules, 'oxlint')) }] : [],
  };
}

/** Type-aware rules switched off, in Biome's group/rule layout. */
function biomeOff(rules) {
  const byGroup = {};
  for (const { biome } of rules.filter((r) => r.typed)) {
    const [group, name] = biome.split('/');
    (byGroup[group] ??= {})[name] = 'off';
  }
  return byGroup;
}

function biomeConfig(fixture, rules) {
  const byGroup = {};
  for (const { biome } of rules) {
    const [group, name] = biome.split('/');
    (byGroup[group] ??= {})[name] = 'error';
  }
  return {
    root: true,
    vcs: { enabled: false },
    files: {
      maxSize: 64 * 1024 * 1024,
      includes: [...SOURCE_FILES, ...scopeIgnores(fixture).map((p) => `!${p}`)],
    },
    // Parameter decorators (e.g. VS Code's dependency injection) are valid
    // TypeScript, but Biome only parses them when this is enabled.
    javascript: { parser: { unsafeParameterDecoratorsEnabled: true } },
    formatter: { enabled: false },
    assist: { enabled: false },
    linter: { enabled: true, rules: { preset: 'none', ...byGroup } },
    overrides: untypedFiles(fixture).length ? [{ includes: untypedFiles(fixture), linter: { rules: biomeOff(rules) } }] : [],
  };
}

fs.rmSync(CONFIGS_DIR, { recursive: true, force: true });
for (const [group, { tools, rules }] of Object.entries(groups)) {
  for (const fixture of FIXTURES) {
    const dir = path.join(CONFIGS_DIR, `group-${group.toLowerCase()}`, fixture);
    fs.mkdirSync(dir, { recursive: true });
    if (tools.includes('eslint')) fs.writeFileSync(path.join(dir, 'eslint.config.mjs'), eslintConfig(group, fixture, rules));
    if (tools.includes('rslint')) fs.writeFileSync(path.join(dir, 'rslint.config.mjs'), rslintConfig(group, fixture, rules));
    if (tools.includes('oxlint')) writeJson(path.join(dir, 'oxlintrc.json'), oxlintConfig(fixture, rules));
    if (tools.includes('biome')) writeJson(path.join(dir, 'biome.json'), biomeConfig(fixture, rules));
  }
  console.log(`group ${group}: ${FIXTURES.length} fixtures x ${tools.join(', ')}`);
}
